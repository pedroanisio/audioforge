#!/usr/bin/env python3
"""Generate `tracks/blue_in_five.af` — a ~5 minute medium-swing jazz quartet.

Form: 8-bar changes in F major (I VI ii V / iii VI ii V), looped by the
rhythm section for the whole track. Arrangement is automation-driven:
  intro -> head in -> tenor solo -> vibes solo -> head out -> outro.
Tenor (head + solo) = `blown`, vibes = `modal`, piano comp = `fm` (Rhodes),
walking bass = `pluck` (upright-ish), plus a brushed swing kit.
"""

OUT = "tracks/blue_in_five.af"

# ---- 8-bar changes (one chord per bar) -------------------------------------
# Fmaj7 | Dm7 | Gm7 | C7 | Am7 | D7 | Gm7 | C7
COMP = ["F3maj7", "D3min7", "G3min7", "C37",
        "A3min7", "D37", "G3min7", "C37"]
SAX  = ["F4maj7", "D4min7", "G4min7", "C47",
        "A4min7", "D47", "G4min7", "C47"]

# ---- Walking bass: four quarter notes per bar (upright register) -----------
WALK = [
    ["F1", "A1", "C2", "E2"],   # Fmaj7
    ["D2", "F2", "A2", "G2"],   # Dm7
    ["G1", "Bb1", "D2", "F2"],  # Gm7
    ["C2", "E2", "G2", "Bb2"],  # C7
    ["A1", "C2", "E2", "G2"],   # Am7
    ["D2", "F#2", "A2", "C3"],  # D7
    ["G1", "Bb1", "D2", "F2"],  # Gm7
    ["C2", "G1", "B1", "Bb1"],  # C7  (chromatic turn back to F)
]

# ---- The head (8 bars, 32 beats): pitch, start-beat, dur-beats, velocity ----
HEAD = [
    ("A4", 0, 1, .70), ("C5", 1, 1, .72), ("F5", 2, 1.5, .82), ("E5", 3.5, .5, .70),
    ("D5", 4, 1.5, .74), ("C5", 5.5, .5, .66), ("A4", 6, 2, .70),
    ("Bb4", 8, 1, .70), ("D5", 9, 1, .74), ("G5", 10, 1.5, .82), ("F5", 11.5, .5, .70),
    ("E5", 12, 1, .74), ("D5", 13, 1, .70), ("Bb4", 14, 2, .68),
    ("C5", 16, 1, .72), ("E5", 17, 1, .76), ("A5", 18, 1.5, .86), ("G5", 19.5, .5, .72),
    ("F#5", 20, 1.5, .78), ("A5", 21.5, .5, .72), ("D5", 22, 2, .74),
    ("Bb4", 24, 1, .70), ("C5", 25, 1, .72), ("D5", 26, 1.5, .76), ("F5", 27.5, .5, .72),
    ("G4", 28, 1.5, .70), ("A4", 29.5, .5, .66), ("C5", 30, 2, .66),
]

HEAD_IN = 32     # bar 9  (~14.5 s)
HEAD_OUT = 544   # bar 137 (~247 s)


def head_notes():
    out = []
    for off in (HEAD_IN, HEAD_OUT):
        for p, b, d, v in HEAD:
            out.append(f"{p} @ {b + off}b for {d}b vel {v}")
    return out


def comp_notes():
    # two swung stabs per bar (downbeat + the 'and of 2')
    out = []
    for bar, ch in enumerate(COMP):
        base = bar * 4
        out.append(f"{ch} @ {base}b for 1.4b vel 0.42 voicing drop2")
        out.append(f"{ch} @ {base + 2.5}b for 1.0b vel 0.36 voicing drop2")
    return out


def walk_notes():
    out = []
    for bar, beats in enumerate(WALK):
        base = bar * 4
        for i, p in enumerate(beats):
            out.append(f"{p} @ {base + i}b for 0.92b vel {0.6 if i % 2 == 0 else 0.52}")
    return out


def arp_notes(chords):
    return [f"{ch} @ {bar * 4}b for 4b" for bar, ch in enumerate(chords)]


def fmt(notes, indent=11):
    pad = " " * indent
    return (",\n" + pad).join(notes)


